var updateStationObservationsFixture = flag.Bool("update-station-observations", false, "write the browser station observations HTTP fixture")

type stationObservationReason struct {
	Reason string `json:"reason"`
	Count  int    `json:"count"`
}

type stationObservationExpected struct {
	ID                    string                     `json:"id"`
	PendingOriginRequests int                        `json:"pendingOriginRequests"`
	DispatchReasons       []stationObservationReason `json:"dispatchReasons"`
}

type stationObservationHTTPCase struct {
	Name     string                       `json:"name"`
	Envelope jsontext.Value               `json:"envelope"`
	Expected []stationObservationExpected `json:"expected"`
}

// TestStationObservationsHTTPFixture pins actual HTTP wire output, not a
// hand-written approximation of the packed request fields. Run with
// -update-station-observations after an approved wire change alters the fixture.
func TestStationObservationsHTTPFixture(t *testing.T) {
	config := project.Default()
	config.IncidentContract = sim.IncidentV1Contract
	shared, err := NewWithProject(config)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(shared.Close)
	frame, err := shared.presentationFrame()
	if err != nil {
		t.Fatal(err)
	}
	topology := shared.Topology()
	// Normalize random process/session identities before encoding. No clock
	// advances, command receipts, or wall-clock timestamps enter this fixture.
	topology.ServerStart, topology.Epoch, topology.ProjectRevision = "station-fixture-server", "station-fixture-epoch", 7
	frame.State.ServerStart, frame.State.Epoch, frame.State.ProjectRevision = topology.ServerStart, topology.Epoch, topology.ProjectRevision
	frame.State.Revision, frame.State.Generation = 120, 2
	if len(frame.State.Simulation.Vehicles) == 0 {
		t.Fatal("fixture needs the default fleet")
	}
	queued := []sim.Request{
		{ID: 1, From: "harbor", To: "market", PartySize: 1, SharingConsent: sim.SharedConsent, Service: sim.OnDemandService, PodID: frame.State.Simulation.Vehicles[0].Pod.ID},
		{ID: 2, From: "harbor", LegFrom: "garden", To: "market", PartySize: 1, SharingConsent: sim.SharedConsent, Service: sim.OnDemandService, DispatchReason: "\ufeffÀ quai 東京"},
	}
	fixture := struct {
		Status string                       `json:"status"`
		Cases  []stationObservationHTTPCase `json:"cases"`
	}{Status: "GENERATED BY EncodeStateJSON", Cases: []stationObservationHTTPCase{}}
	for _, test := range []struct {
		name    string
		pending []sim.Request
	}{
		{"queued", queued},
		{"empty-queue", nil},
	} {
		frame.State.Simulation.Pending = test.pending
		frame.State.Simulation.Submitted = len(test.pending)
		raw, encodeErr := EncodeStateJSON(topology, frame)
		if encodeErr != nil {
			t.Fatalf("%s EncodeStateJSON: %v", test.name, encodeErr)
		}
		if _, decodeErr := DecodeStateJSON(raw); decodeErr != nil {
			t.Fatalf("%s DecodeStateJSON: %v", test.name, decodeErr)
		}
		assertStationObservationPackedRequests(t, raw, test.pending)
		expected := []stationObservationExpected{}
		for _, station := range topology.Network.Stations {
			entry := stationObservationExpected{ID: station.ID, DispatchReasons: []stationObservationReason{}}
			reasons := map[string]int{}
			for _, request := range test.pending {
				origin := request.From
				if request.LegFrom != "" {
					origin = request.LegFrom
				}
				if origin == station.ID {
					entry.PendingOriginRequests++
					reasons[request.DispatchReason]++
				}
			}
			keys := make([]string, 0, len(reasons))
			for reason := range reasons {
				keys = append(keys, reason)
			}
			slices.Sort(keys)
			for _, reason := range keys {
				entry.DispatchReasons = append(entry.DispatchReasons, stationObservationReason{Reason: reason, Count: reasons[reason]})
			}
			expected = append(expected, entry)
		}
		fixture.Cases = append(fixture.Cases, stationObservationHTTPCase{Name: test.name, Envelope: raw, Expected: expected})
	}
	raw, err := jsonv2.Marshal(fixture)
	if err != nil {
		t.Fatal(err)
	}
	value := jsontext.Value(raw)
	if indentErr := value.Indent(jsontext.WithIndent("  ")); indentErr != nil {
		t.Fatal(indentErr)
	}
	value = append(value, '\n')
	_, source, _, ok := runtime.Caller(0)
	if !ok || !filepath.IsAbs(source) {
		t.Fatal("fixture test needs an absolute source path; run go test without -trimpath")
	}
	path := filepath.Join(filepath.Dir(source), "..", "..", "web", "testdata", "station-observations.json")
	if *updateStationObservationsFixture {
		if writeErr := os.WriteFile(path, value, 0o600); writeErr != nil {
			t.Fatal(writeErr)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, value) {
		t.Fatal("station observations HTTP fixture differs; rerun this test with -update-station-observations, then run the Node parity test")
	}
}

func assertStationObservationPackedRequests(t *testing.T, raw []byte, source []sim.Request) {
	t.Helper()
	var wire struct {
		Frame struct {
			State struct {
				Simulation struct {
					Pending []map[string]jsontext.Value `json:"pending"`
				} `json:"simulation"`
			} `json:"state"`
		} `json:"frame"`
	}
	if err := jsonv2.Unmarshal(raw, &wire); err != nil {
		t.Fatal(err)
	}
	if len(wire.Frame.State.Simulation.Pending) != len(source) {
		t.Fatal("encoded pending count differs from source")
	}
	for i, request := range source {
		fields := map[string]string{"from": request.From, "to": request.To, "podID": request.PodID, "dispatchReason": request.DispatchReason, "serviceID": request.ServiceID, "legFrom": request.LegFrom}
		for name, plain := range fields {
			token, present := wire.Frame.State.Simulation.Pending[i][name]
			if (name == "serviceID" || name == "legFrom") && plain == "" {
				if present {
					t.Fatalf("empty omitempty field %s is present", name)
				}
				continue
			}
			want := `"` + base64.StdEncoding.EncodeToString([]byte(plain)) + `"`
			if !present || string(token) != want {
				t.Fatalf("pending %d field %s: got %s, want literal canonical %s", i, name, token, want)
			}
		}
	}
}
